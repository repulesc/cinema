#!/usr/bin/env python3
"""Builds the Lite scripts (hud-lite/src) from the full ones (hud/src): same code, `integer LITE = 0;`
becomes `integer LITE = 1;` in cinema_core, cinema_ui and cinema_scenery. Lite = scenery camera (outdoor
views), AFK, double-tap / tap / hold, Pace, Photo hold, the classic look. Personal, Social, Friends, skybox
rooms, favourites, look choice and chat cuts stay in the full version: their scripts (cinema_people,
cinema_friends, cinema_picker) are simply not part of Lite.

    python3 tools/build_lite.py            write hud-lite/src/*.lsl
    python3 tools/build_lite.py --check    fail if the committed hud-lite/src is out of date (CI)
"""
import os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC, OUT = os.path.join(ROOT, "hud", "src"), os.path.join(ROOT, "hud-lite", "src")
FILES = ["cinema_core.lsl", "cinema_ui.lsl", "cinema_scenery.lsl"]

def lite(name):
    s = open(os.path.join(SRC, name)).read()
    assert s.count("integer LITE    = 0;") == 1, f"{name}: LITE switch not found exactly once"
    s = s.replace("integer LITE    = 0;", "integer LITE    = 1;")
    if name == "cinema_ui.lsl":
        assert s.count('string NOTECARD = "Take 12 - Read Me";') == 1
        s = s.replace('string NOTECARD = "Take 12 - Read Me";', 'string NOTECARD = "Take 12 Lite - Read Me";')
    return "// *** LITE BUILD, generated by tools/build_lite.py from hud/src: do not edit by hand ***\n" + s

def main():
    check = "--check" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    bad = []
    for n in FILES:
        text = lite(n); path = os.path.join(OUT, n)
        if check:
            if not os.path.exists(path) or open(path).read() != text: bad.append(n)
        else:
            open(path, "w").write(text)
    if check:
        if bad: print("hud-lite/src is out of date, run tools/build_lite.py:", ", ".join(bad)); raise SystemExit(1)
        print("hud-lite/src is up to date")
    else:
        print("wrote", len(FILES), "Lite scripts to hud-lite/src")

if __name__ == "__main__":
    main()
