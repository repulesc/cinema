#!/usr/bin/env python3
"""Builds the free Take 12 Scenery scripts (scenery/src) from the full ones (hud/src).

Same code, four scripts: core, ui, scenery and tips. `integer LITE = 0;` becomes `= 1;` (core takes only the scenery
camera, ui hides the other cameras and sharing and shows "More cameras", scenery keeps no favourites), and a few texts
are swapped for the free build's own (and the Button choice is left out: it has one button design, scenery/art),
so the full build carries none of them. people, friends, picker, frame, lens
and sync are simply not part of it. Every substitution must match exactly once, so a change in hud/src that moves one
fails here instead of shipping a stale text.

    python3 tools/build_scenery.py            write scenery/src/*.lsl
    python3 tools/build_scenery.py --check    fail if the committed scenery/src is out of date (CI)
"""
import os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC, OUT = os.path.join(ROOT, "hud", "src"), os.path.join(ROOT, "scenery", "src")
HEADER = "// *** TAKE 12 SCENERY (free), generated by tools/build_scenery.py from hud/src: do not edit by hand ***\n"
LITE = ("integer LITE    = 0;", "integer LITE    = 1;")

SUBS = {
    "core.lsl": [LITE],
    "scenery.lsl": [LITE],
    "ui.lsl": [
        LITE,
        ('string NOTECARD = "Take 12 - Read Me";', 'string NOTECARD = "Take 12 Scenery - Read Me";'),
        ('string h = "Take 12";', 'string h = "Take 12 Scenery";'),
        ('llOwnerSay("[Take 12] Tap: menu. Double-tap: scenery, or the next view. Hold: connect with people near you. Commands: /" + cfgGet("cmd_chan") + " help");',
         'llOwnerSay("[Take 12 Scenery] Tap: menu. Double-tap: scenery, or the next view. Any movement key: your camera back.");'),
        ('"Framing · you, or you and the people with you, composed\\nFreehand · you frame it, it holds it\\nConnect · one camera for everyone near you\\nScenery · the place, while you are away\\nFormat · the shape of the picture"',
         '"Scenery · the place, while you are away\\nMore cameras · Framing, Freehand and Connect, in the full Take 12"'),
        ('"Welcome to Take 12\\nTap: menu\\nDouble-tap: scenery, or the next view\\nHold: connect with people near you\\nAny movement key: your camera back"',
         '"Welcome to Take 12 Scenery\\nTap: menu\\nDouble-tap: scenery, or the next view\\nAny movement key: your camera back"'),
        ('\\nLook · the button, the line above it, its size\\nCamera · seated view, Alt-cam, chat cuts', '\\nLook · the line above the button, chat text\\nCamera · Alt-cam, phantom'),
        ('"Seated view: " + seatText() + " · Alt-cam: "', '"Alt-cam: "'),
        ('+ "\\nChat cuts: " + onoff("chat_cuts") + " · Phantom (see-through objects block the camera too): "', '+ "\\nPhantom (see-through objects block the camera too): "'),
        # one button design (scenery/art): no Button choice under Look; no Size (no keys.lsl); Frame, Framing,
        # Freehand and Connect are hidden by locked()
        ('text += "Button: " + llList2String(["Classic", "Rec", "Viewfinder"], gLook)', 'text += "Look"'),
        ('b = ["th0", "th1", "th2", "stline", "size", "trace", "back"];', 'b = ["stline", "trace", "back"];'),
    ],
    "tips.lsl": [
        ('"Take 12\\nTap: menu · Double-tap: scenery · Hold: connect"', '"Take 12 Scenery\\nTap: menu · Double-tap: scenery"'),
        ('"Tap while it rolls\\ntap: next, stop, connect, cameras"', '"Tap while it rolls\\ntap: photo, next, stop"'),
        ('string  NEED = "core scenery people friends picker frame free lens sync connect crop keys fit";', 'string  NEED = "core scenery";'),
    ],
}
FILES = list(SUBS)

def build(name):
    s = open(os.path.join(SRC, name)).read()
    for a, b in SUBS[name]:
        assert s.count(a) == 1, f"{name}: expected exactly one {a!r}, found {s.count(a)}"
        s = s.replace(a, b)
    return HEADER + s

def main():
    check = "--check" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    bad = []
    for n in FILES:
        text, path = build(n), os.path.join(OUT, n)
        if check:
            if not os.path.exists(path) or open(path).read() != text: bad.append(n)
        else:
            open(path, "w").write(text)
    if check:
        if bad: print("scenery/src is out of date, run python3 tools/build_scenery.py:", ", ".join(bad)); raise SystemExit(1)
        print("scenery/src is up to date")
    else:
        print("wrote", len(FILES), "Take 12 Scenery scripts to scenery/src")

if __name__ == "__main__":
    main()
