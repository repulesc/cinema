#!/usr/bin/env python3
"""Builds the free Take 12 Scenery scripts (scenery/src) from the full ones (hud/src), 8.0.

Same code, nine of the twelve scripts: core, ui, text, screen, strip, bars, scenic, sync and carry. `integer LITE   = 0;`
becomes `= 1;` where a script has the switch (core starts only Scenic, strip dims TRACKING, PORTRAIT and FIXED and
says "In the full Take 12." on a tap, text names it Take 12 Scenery, sync can watch a friend's film but never films
for others, carry always gives way to a full Take 12 worn with it); screen, bars and scenic are copied as they are. tracking,
portrait and fixed are simply not part of it. Every substitution must match exactly once, so a change in hud/src that
moves one fails here instead of shipping a stale build.

    python3 tools/build_scenery.py            write scenery/src/*.lsl
    python3 tools/build_scenery.py --check    fail if the committed scenery/src is out of date (CI)
"""
import os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC, OUT = os.path.join(ROOT, "hud", "src"), os.path.join(ROOT, "scenery", "src")
HEADER = "// *** TAKE 12 SCENERY (free), generated by tools/build_scenery.py from hud/src: do not edit by hand ***\n"
LITE = ("integer LITE   = 0;", "integer LITE   = 1;")

SUBS = {
    "core.lsl": [LITE],
    "ui.lsl": [LITE],
    "text.lsl": [LITE],
    "screen.lsl": [],
    "strip.lsl": [LITE],
    "bars.lsl": [],
    "scenic.lsl": [],
    "sync.lsl": [LITE],
    "carry.lsl": [LITE],
}
FILES = list(SUBS)


def build(name):
    s = open(os.path.join(SRC, name)).read()
    for a, b in SUBS[name]:
        assert s.count(a) == 1, f"{name}: expected exactly one {a!r}, found {s.count(a)}"
        s = s.replace(a, b)
    return HEADER + s


def main():
    check = "--check" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    bad = []
    for n in FILES:
        text, path = build(n), os.path.join(OUT, n)
        if check:
            if not os.path.exists(path) or open(path).read() != text: bad.append(n)
        else:
            open(path, "w").write(text)
    extra = sorted(set(os.listdir(OUT)) - set(FILES))
    if check:
        if extra: bad += extra
        if bad: print("scenery/src is out of date, run python3 tools/build_scenery.py:", ", ".join(bad)); raise SystemExit(1)
        print("scenery/src is up to date")
    else:
        for n in extra: os.remove(os.path.join(OUT, n))
        print("wrote", len(FILES), "Take 12 Scenery scripts to scenery/src")


if __name__ == "__main__":
    main()
