#!/usr/bin/env python3
"""Builds the free Take 12 Scenery scripts (scenery/src) from the full ones (hud/src).

Same code, four scripts: core, ui, scenery and tips. `integer LITE = 0;` becomes `= 1;` (core takes only the scenery
camera, ui hides the other cameras and sharing and shows "More cameras", scenery keeps no favourites), and a few texts
are swapped for the free build's own (and the Button choice is left out: it has one button design, scenery/art),
so the full build carries none of them. people, friends, picker, frame, lens
and sync are simply not part of it. Every substitution must match exactly once, so a change in hud/src that moves one
fails here instead of shipping a stale text.

    python3 tools/build_scenery.py            write scenery/src/*.lsl
    python3 tools/build_scenery.py --check    fail if the committed scenery/src is out of date (CI)
"""
import os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC, OUT = os.path.join(ROOT, "hud", "src"), os.path.join(ROOT, "scenery", "src")
HEADER = "// *** TAKE 12 SCENERY (free), generated by tools/build_scenery.py from hud/src: do not edit by hand ***\n"
LITE = ("integer LITE    = 0;", "integer LITE    = 1;")

SUBS = {
    "core.lsl": [LITE],
    "scenery.lsl": [LITE],
    "ui.lsl": [
        LITE,
        ('string NOTECARD = "Take 12 - Read Me";', 'string NOTECARD = "Take 12 Scenery - Read Me";'),
        ('string h = "Take 12";', 'string h = "Take 12 Scenery";'),
        ('llOwnerSay("[Take 12] Tap: menu. Double-tap: scenery, or the next view. Hold: share your view. Commands: /" + cfgGet("cmd_chan") + " help");',
         'llOwnerSay("[Take 12 Scenery] Tap: menu. Double-tap: scenery, or the next view. Any movement key: your camera back.");'),
        ('"Scenery · the place, while you are away\\nMe · follows you\\nUs · you and the people around you\\nStill · a held picture of you\\nFreehand · you frame it, it holds the shot\\nFrame · the picture format on your screen"',
         '"Scenery · the place, while you are away\\nMore cameras · Me, Us, Still, Freehand and sharing, in the full Take 12"'),
        ('"Welcome to Take 12\\nTap: menu\\nDouble-tap: scenery, or the next view\\nHold: share your view\\nAny movement key: your camera back"',
         '"Welcome to Take 12 Scenery\\nTap: menu\\nDouble-tap: scenery, or the next view\\nAny movement key: your camera back"'),
        ('Camera · seated view, indoors, reach, Alt-cam, chat cuts', 'Camera · indoors, reach, Alt-cam'),
        ('"Seated view: " + seatText() + " · Indoors: "', '"Indoors: "'),
        ('+ "\\nChat cuts: " + onoff("chat_cuts") + " · Phantom: "', '+ "\\nPhantom: "'),
        # Photo hold stays here (6.6 took it out of the full menu: the full HUD has Freehand and the HOLD key)
        ('~resume|▶|›|Resume~', '~photo|📷|▣|Photo~resume|▶|›|Resume~'),
        ('if (gUiState == "frozen") b = ["resume"];         // held (the HOLD key while live, /77 photo): carry on',
         'if (gUiState == "frozen") b = ["resume"]; else b = ["photo"];'),
        ('if (id == "resume") llMessageLinked(LINK_SET, CMD, "photo", "");', 'if (id == "photo" || id == "resume") llMessageLinked(LINK_SET, CMD, "photo", "");'),
        # no Frame (crop.lsl is not part of it)
        ('b = ["scenery", "personal", "us", "frame", "free", "crop", "share", "opts", "full", "help", "close"];', 'b = ["scenery", "personal", "us", "frame", "free", "share", "opts", "full", "help", "close"];'),
        # one button design (scenery/art): no Button choice under Options > Look
        ('Look · menu style, button, chat text', 'Look · menu style, status line, chat text'),
        (' + " · Button: " + llList2String(["Classic", "Rec", "Viewfinder"], gLook)', ''),
        ('b = ["sk0", "sk1", "sk2", "th0", "th1", "th2", "stline", "trace", "back"];', 'b = ["sk0", "sk1", "sk2", "stline", "trace", "back"];'),
    ],
    "tips.lsl": [
        ('"Take 12\\nTap: menu · Double-tap: scenery · Hold: share"', '"Take 12 Scenery\\nTap: menu · Double-tap: scenery"'),
        ('"Tap while it rolls\\ntap: next, stop, share, cameras"', '"Tap while it rolls\\ntap: photo, next, stop"'),
    ],
}
FILES = list(SUBS)

def build(name):
    s = open(os.path.join(SRC, name)).read()
    for a, b in SUBS[name]:
        assert s.count(a) == 1, f"{name}: expected exactly one {a!r}, found {s.count(a)}"
        s = s.replace(a, b)
    return HEADER + s

def main():
    check = "--check" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    bad = []
    for n in FILES:
        text, path = build(n), os.path.join(OUT, n)
        if check:
            if not os.path.exists(path) or open(path).read() != text: bad.append(n)
        else:
            open(path, "w").write(text)
    if check:
        if bad: print("scenery/src is out of date, run python3 tools/build_scenery.py:", ", ".join(bad)); raise SystemExit(1)
        print("scenery/src is up to date")
    else:
        print("wrote", len(FILES), "Take 12 Scenery scripts to scenery/src")

if __name__ == "__main__":
    main()
