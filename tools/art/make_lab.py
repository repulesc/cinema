#!/usr/bin/env python3
"""The Take 12 Lab's marks texture (lab/art/take12_marks_1024.png): the product's marks (make_strip.py), every cell where
it is, plus the lab's three in the free space of the last row: the fold key (› opens the Direct page, ‹ folds it) and
the Quiet page's notch (black with rounded lower corners, tinted by screen.lsl; turned over for a strip at the bottom).
The cell tables are written into lab/src/strip.lsl and lab/src/screen.lsl, as make_strip.py does for the product.

    python3 tools/art/make_lab.py           # writes the PNG and the tables
    python3 tools/art/make_lab.py --check   # CI: fails if the lab's tables are stale
"""
import os, sys
from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_strip as M

LAB = os.path.join(M.ROOT, "lab")
CELL_H = M.CELL_H


def chevron(right):
    im, k = M.ss(64, CELL_H)
    d = ImageDraw.Draw(im)
    cx, cy, h, w = 32, 24, 7.0, 4.5
    pts = [(cx - w * 0.5, cy - h), (cx + w * 0.5, cy), (cx - w * 0.5, cy + h)] if right else \
          [(cx + w * 0.5, cy - h), (cx - w * 0.5, cy), (cx + w * 0.5, cy + h)]
    d.line([(x * k, y * k) for x, y in pts], fill=M.WHITE + (255,), width=int(2.4 * k), joint="curve")
    for x, y in (pts[0], pts[2]):                      # round ends
        r = 1.2 * k
        d.ellipse([x * k - r, y * k - r, x * k + r, y * k + r], fill=M.WHITE + (255,))
    return M.down(im, 64, CELL_H)


def tab():
    """the notch: full height of the cell, square at the top (it meets the screen's edge or the band), its lower corners
    rounded (12 of 48: about 10 px on the 40 px strip)"""
    im, k = M.ss(512, CELL_H)
    d = ImageDraw.Draw(im)
    r = 12 * k
    d.rounded_rectangle([0, -r, 512 * k - 1, CELL_H * k - 1], radius=r, fill=(255, 255, 255, 255))
    return M.down(im, 512, CELL_H)


def marks():
    sheet, table = M.marks()
    y = 512 + 6 * CELL_H                                 # the shutter's and the Orbit's row; free after x 256
    for name, im, x in (("foldR", chevron(True), 256), ("foldL", chevron(False), 320), ("tab", tab(), 384)):
        sheet.alpha_composite(im, (x, y))
        table.append((name, x, y, im.width, im.height, im.width))
    return sheet, table


def tables(wt, mt):
    scr = M.SCREEN_MARKS + ("tab",)
    w = "~" + "~".join("%s|%d|%d|%d" % r for r in wt) + "~"
    ms = "~" + "~".join("%s|%d|%d|%d|%d|%d" % r for r in mt if r[0] not in scr + M.UNUSED) + "~"
    mk = "~" + "~".join("%s|%d|%d|%d|%d|%d" % r for r in mt if r[0] in scr) + "~"
    strip = "\n".join(["// <CELLS> (generated by tools/art/make_lab.py: do not edit)",
                       "// WORDS: ~name|x|y|width px~ (cells 512 x 48 on take12_words); MARKS: ~name|x|y|w|h|content width~",
                       M._split("string WORDS = ", w), M._split("string MARKS = ", ms), "// </CELLS>"])
    screen = "\n".join(["// <MARKS> (generated by tools/art/make_lab.py: do not edit)",
                        "// MARKS: ~name|x|y|w|h|content width~ on take12_marks (the lab's)", M._split("string MARKS = ", mk), "// </MARKS>"])
    return strip, screen


if __name__ == "__main__":
    _, wt = M.words()
    ms, mt = marks()
    strip_t, screen_t = tables(wt, mt)
    stale = []
    for name, t, tag in (("strip.lsl", strip_t, "CELLS"), ("screen.lsl", screen_t, "MARKS")):
        path = os.path.join(LAB, "src", name)
        src = open(path, encoding="utf-8").read()
        new = M.splice(src, t, tag)
        if new != src:
            stale.append(name)
            if "--check" not in sys.argv: open(path, "w", encoding="utf-8").write(new)
    if "--check" in sys.argv:
        if stale: raise SystemExit("make_lab: the tables in lab/src/%s are stale; run python3 tools/art/make_lab.py" % ", ".join(stale))
        print("make_lab: the lab's tables match its marks")
        sys.exit(0)
    os.makedirs(os.path.join(LAB, "art"), exist_ok=True)
    ms.save(os.path.join(LAB, "art", "take12_marks_1024.png"))
    print("wrote lab/art/take12_marks_1024.png and the tables in lab/src/strip.lsl and screen.lsl")
