"""The [12]'s gestures and the setup (8.0), on the REAL scripts: the first wear (a note, nothing pops up), the first
run (lens with a live mm reading, the eye line with PgUp / PgDn and a tap, the size, the tour), tap = the dialog
0.35 s later, double-tap = the strip, hold = everything off and hold again = back exactly, every dialog page within
SL's limits, /12 commands, a re-wear starting clean (no text from yesterday, no shot running)."""
from emu_util import *

# ---- the first wear and the first run ---------------------------------------------------------------------------
w = World()
ana = w.avatar("Ana", (128, 128, 21))
h = ana.wear(HUD_SCRIPTS, lsd={"cin.owner": (str(ana.key), PASS)})
w.run(5)
check(ana.notes() == ["Tap the [12] to set up."], "first wear: one note, %r" % ana.notes())
check(ana.dialog is None, "first wear: nothing pops up")
ana.tap(); w.run(0.2)
check(ana.dialog is None, "the dialog waits 0.35 s for a second tap")
w.run(0.5)
dialog_ok(ana, "first")
check(ana.labels() == ["Start", "Later"], "first: %r" % ana.labels())
ana.click("Start"); w.run(0.5)
dialog_ok(ana, "lens")
check("Skip" in ana.labels() and "● 38 mm" in ana.labels() and sorted(l for l in ana.labels() if l.endswith("mm")) == ["21 mm", "26 mm", "32 mm", "47 mm", "56 mm", "● 38 mm"], "lens (first run): the viewer's stops, 38 mm by default: %r" % ana.labels())
w.run(2.1)
check(any(n.endswith(" mm") and n.split()[0].isdigit() for n in ana.notes()), "lens: the live mm shows on the [12]")
ana.click("47 mm"); w.run(0.5)
check(lsd(h, "lens") == "47", "lens kept: %r" % lsd(h, "lens"))
check(var(h, "ui", "gEye") == 1, "the eye line starts after the lens")
cam, foc, scripted = ana.camera()
check(scripted and abs(cam[2] - foc[2]) < 0.01 and 2.0 < B.llVecDist(cam, ana.pos) < 3.0, "eye line: a level camera in front of you %s" % (cam,))
check(any("PgUp" in n for n in ana.notes()), "eye line: the note says how")
eye0 = lsd(h, "eye")
for i in range(6): ana.keys(C["CONTROL_UP"], hold=0.1); w.run(0.3)
z = var(h, "ui", "gEyeZ")
check(z > 0.02, "PgUp moves the line up (%.3f)" % z)
check(abs(rect(h, ana, "t12 u2")[1] - z) < 0.002 and rect(h, ana, "t12 u2")[4] > 0.5, "the line is on the screen at %.3f" % z)
ana.tap(); w.run(0.6)
e = float(lsd(h, "eye") or 0)
check(0.6 < e < 1.0 and lsd(h, "eye") != eye0, "the eye line is kept as a fraction of your height: %r" % lsd(h, "eye"))
check(not var(h, "core", "gEyeOn") and var(h, "core", "gState") == "wait", "the camera is yours again after the eye line")
dialog_ok(ana, "size")
check(ana.labels() == ["Smaller", "Good", "Larger"], "size: %r" % ana.labels())
check(var(h, "screen", "gOpen") == 1, "the strip is open to judge its size")
ana.click("Larger"); w.run(0.5)
check(lsd(h, "size") == "l", "Larger: size L")
ana.click("Good"); w.run(0.5)
dialog_ok(ana, "inview")
check(ana.labels() == ["Yes", "Lower it"], "is the whole strip in view: %r" % ana.labels())
# 8.5.7: a viewer whose bars are taller than one step (a tester's strip sat partly under them): every press moves the strip a
# step (40 px) further from the edge, up to 6, and nothing in the setup is a dead end any more
y0 = rect(h, ana, "Take 12")[1]
last = y0
for k in range(1, 9):
    ana.click("Lower it"); w.run(0.5)
    want = min(k, 6)
    y = rect(h, ana, "Take 12")[1]
    check(lsd(h, "drop") == str(want) and abs((y0 - y) - 40 * want / 1080.0) < 1e-3, "Lower it x%d: %d steps in (%r, %.0f px)" % (k, want, lsd(h, "drop"), (y0 - y) * 1080))
band = rect(h, ana, "t12 band")
check(abs(band[3] - (50 + 240) / 1080.0) < 2e-3, "the band is black all the way down to the strip (%.0f px)" % (band[3] * 1080))
ana.click("Yes"); w.run(0.5)
for p in ("tour1", "tour2"):
    dialog_ok(ana, p)
    ana.click("Next ›"); w.run(0.5)
dialog_ok(ana, "tour3")
ana.click("Done"); w.run(0.5)
check(lsd(h, "firstrun") == "done", "the first run is done")
check(var(h, "screen", "gOpen") == 1, "the setup leaves the strip open (8.0.4)")
w.run(3)
check(var(h, "tracking", "gAuto") == 1 and var(h, "strip", "gAuto") == 1 and state(h) == ("film", "tracking"),
      "after the setup, Auto directs: Tracking, holding behind you (8.4.0) %r" % (state(h),))
h.send(7371, "stop"); w.run(1)                                       # the lit hold: your viewer's camera, and manual
check(var(h, "tracking", "gAuto") == 0 and state(h) == ("wait", ""), "your viewer's camera: Auto stops")
no_errors(w, "first run")

# ---- the gestures ----------------------------------------------------------------------------------------------------
ana.chat.clear()
ana.tap(); w.run(0.6)
dialog_ok(ana, "main")
check(var(h, "ui", "gBtn") == ["Connect", "Settings", "Help", "Feedback", "Close"], "main (Feedback in beta, 8.0.10): %r" % var(h, "ui", "gBtn"))
check("Your own camera" in ana.dialog[1] and "Tip:" in ana.dialog[1], "main: the state and a tip: %r" % ana.dialog[1])
# every page within SL's limits, and Back always leads up
ana.click("Settings"); w.run(0.5)
dialog_ok(ana, "settings")
pages = [b for b in ana.labels() if b not in ("‹ Back", "Eye line")]
for p in pages:
    ana.click(p); w.run(0.5)
    dialog_ok(ana, p)
    if p == "Look":
        ana.click("Place"); w.run(0.5)
        dialog_ok(ana, "place")
        ana.click("Bottom"); w.run(0.5)
        check(lsd(h, "place") == "bot", "Place › Bottom")
        ana.click("Move in"); w.run(0.5)
        check(lsd(h, "drop") == "1", "Place › Move in: a step (choosing Bottom had started over)")
        ana.click("Move in"); w.run(0.5)
        check(lsd(h, "drop") == "2", "Move in again: another")
        ana.click("● Bottom"); w.run(0.5)
        check(lsd(h, "drop") == "0", "choosing a place starts over")
        ana.click("Move in"); w.run(0.5)
        check(lsd(h, "drop") == "1", "Move in: one step")
        ana.say(12, "lower"); w.run(0.5)
        check(lsd(h, "drop") == "2", "/12 lower: a step (when the bars cover the [12] too)")
        ana.click("● Bottom"); w.run(0.3)
        ana.click("‹ Back"); w.run(0.5)
    if p == "Frames & bars":
        check(sorted(b for b in ana.labels() if b.strip()) == sorted(["Film", "Photo", "● Black", "Dimmed", "‹ Back"]), "one film frame, one photo frame (8.5.9): %r" % ana.labels())
        ana.click("Film"); w.run(0.5)
        dialog_ok(ana, "frame")
        check("● 2.39" in ana.labels(), "the film's frame is 2.39: %r" % ana.labels())
        ana.click("2.00"); w.run(0.5)
        check(lsd(h, "shape") == "2.00" and "● 2.00" in ana.labels(), "2.00 kept, for every shot; the page stays")
        ana.click("‹ Back"); w.run(0.5)
        ana.click("Dimmed"); w.run(0.5)
        check(lsd(h, "bstyle") == "dim", "Dimmed bars")
    if p == "Idle start":
        ana.click("Away"); w.run(0.5)
        check(lsd(h, "idle") == "away", "idle: Away")
    if p == "Reset":
        ana.click("Everything"); w.run(0.5)
        check(ana.labels() == ["Yes, reset", "‹ Back"], "Everything asks to confirm: %r" % ana.labels())
        ana.click("‹ Back"); w.run(0.5)
    ana.click("‹ Back"); w.run(0.5)
    check(ana.dialog and "Settings" in ana.dialog[1], "Back from %s leads to Settings" % p)
ana.click("‹ Back"); w.run(0.5)
ana.click("Help"); w.run(0.5)
dialog_ok(ana, "help")
check("Double-tap" in ana.dialog[1], "help card: %r" % ana.dialog[1])
ana.click("‹ Back"); w.run(0.5)
ana.click("Close"); w.run(0.5)
check(ana.dialog is None, "Close")
# double-tap: the strip, no dialog (the setup left it open: closes, then opens)
ana.double_tap(); w.run(1.0)
check(var(h, "screen", "gOpen") == 0 and ana.dialog is None, "double-tap closes the strip, no dialog")
ana.double_tap(); w.run(1.0)
check(var(h, "screen", "gOpen") == 1 and ana.dialog is None, "double-tap opens the strip, no dialog")
ana.touch("t12 s1"); w.run(4)
check(state(h) == ("film", "portrait"), "a shot word starts it: %r" % (state(h),))
# hold: everything off; hold again: back exactly
ana.long_press(); w.run(1.5)
check(state(h)[0] == "off" and not h.cam.get("active"), "hold: everything off (%r, camera %r)" % (state(h), h.cam.get("active")))
check(var(h, "screen", "gOpen") == 0, "hold: the strip closes")
check(all(rect(h, ana, "t12 bar%d" % i)[4] == 0.0 or rect(h, ana, "t12 bar%d" % i)[3] <= 0.0101 for i in range(4)), "hold: the bars go")
check(var(h, "screen", "gHold") == 0, "the hold fill ends")
ana.double_tap(); w.run(1.0)
check(var(h, "screen", "gOpen") == 0, "off: double-tap does nothing")
ana.long_press(); w.run(4)
check(state(h) == ("film", "portrait") and h.cam.get("active"), "hold again: Portrait back (%r)" % (state(h),))
check(var(h, "screen", "gOpen") == 1, "hold again: the strip as it was")
no_errors(w, "gestures")

# ---- /12 commands ---------------------------------------------------------------------------------------------------
ana.say(12, "tracking"); w.run(3)
check(state(h) == ("film", "tracking"), "/12 tracking")
ana.say(12, "bars"); w.run(1)
check(lsd(h, "bars") == "0", "/12 bars turns them off")
ana.say(12, "size s"); w.run(1)
check(lsd(h, "size") == "s", "/12 size s")
ana.say(12, "off"); w.run(1)
check(state(h)[0] == "off", "/12 off")
ana.say(12, "off"); w.run(3)
check(state(h) == ("film", "tracking"), "/12 off again: back")
ana.say(12, "nonsense"); w.run(1)
check(any("/12 auto · tracking" in c[2] for c in ana.chat), "an unknown command lists them")
no_errors(w, "commands")

# ---- re-wear: a clean start ---------------------------------------------------------------------------------------
h.send(7344, "kept|")
w.run(0.5)
check(h.part("t12 note")["text"] != "", "a note on screen")
ana.take_off(h); w.run(1)
h2 = ana.wear(HUD_SCRIPTS, lsd={k: v for k, v in h.lsd.items()})
w.run(2)
check(all(p["text"] == "" for p in h2.prims), "re-wear: no text from before")
check(state(h2) == ("wait", ""), "re-wear: no shot running, %r" % (state(h2),))
w.run(3)
check(state(h2) == ("film", "tracking") and var(h2, "strip", "gAuto") == 1, "re-wear, set up: Auto directs after 3 s %r" % (state(h2),))
check(lsd(h2, "lens") == "47" and lsd(h2, "firstrun") == "done", "re-wear: the setup is kept")
no_errors(w, "re-wear")

# ---- Settings › Screen (8.6.0): place, size and the frames in one page that stays open, so you watch the strip move -----
ana.dialog = None
ana.tap(); w.run(0.8); ana.click("Settings"); w.run(0.5)
check(sorted(b for b in ana.labels() if b.strip()) == sorted(["Camera", "Screen", "Reset", "‹ Back"]), "Settings: Camera, Screen, Reset (%r)" % ana.labels())
ana.click("Screen"); w.run(0.5)
y0 = rect(h2, ana, "Take 12")[1]
check(lsd(h2, "drop") == "6", "the setup's Lower it moved it in 6 steps, the most")
ana.click("Move in"); w.run(0.5)
check(lsd(h2, "drop") == "6", "Move in at the most: nothing")
ana.click("Move out"); w.run(0.5); ana.click("Move out"); w.run(0.5)
check(lsd(h2, "drop") == "4" and abs((rect(h2, ana, "Take 12")[1] - y0) * 1080 - 80) < 1 and "Move in" in ana.labels(), "Screen › Move out twice: 80 px out, the page stays")
ana.click("Move in"); w.run(0.5)
check(lsd(h2, "drop") == "5", "Move in: a step in")
ana.click("L"); w.run(0.5)
check(lsd(h2, "size") == "l" and "● L" in ana.labels(), "L: the larger strip, marked")
ana.click("‹ Back"); w.run(0.5); ana.click("Camera"); w.run(0.5)
check(sorted(b for b in ana.labels() if b.strip()) == sorted(["Lens", "Eye line", "Motion", "Idle start", "Seats", "‹ Back"]), "Camera: lens, eye line, motion, idle, seats (%r)" % ana.labels())
no_errors(w, "screen")
done("gestures_emu")
