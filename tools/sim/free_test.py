# Guards the free Take 12 Scenery build (6.1.0): scenery/src must be hud/src with only the free switch and the free
# texts changed (line for line), it must not mention what it does not have (sharing, Me, Us, Still as its own), the
# scenery camera keeps skybox rooms, and the notecard the HUD gives is the one in scenery/notecard.
import os, re, difflib
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
rd = lambda *p: open(os.path.join(R, *p)).read()
ok = True
def check(c, msg):
    global ok
    if not c: ok = False; print("FAIL", msg)

FILES = ("core.lsl", "ui.lsl", "scenery.lsl", "tips.lsl")
check(sorted(os.listdir(os.path.join(R, "scenery", "src"))) == sorted(FILES), "scenery/src must hold exactly core, ui, scenery and tips")
changed = 0
for n in FILES:
    full, free = rd("hud", "src", n).splitlines(), rd("scenery", "src", n).splitlines()
    check(free[0].startswith("// *** TAKE 12 SCENERY (free), generated by tools/build_scenery.py"), f"{n}: generated header missing")
    free = free[1:]
    check(len(free) == len(full), f"{n}: lines added or removed (only lines may change)")
    for a, b in zip(full, free):
        if a == b: continue
        changed += 1
        check(a.startswith("integer LITE    = 0;") or '"' in a, f"{n}: a code line changed: {b.strip()[:80]}")
    if n in ("core.lsl", "ui.lsl", "scenery.lsl"):
        check("integer LITE    = 1;" in "\n".join(free), f"{n}: the free switch is not on")
    check("Lite" not in "\n".join(free), f"{n}: says Lite")
ui, tips, sc, core = (rd("scenery", "src", n) for n in ("ui.lsl", "tips.lsl", "scenery.lsl", "core.lsl"))
for s, n in ((ui, "ui"), (tips, "tips")):
    for bad in ("Hold: share", "share your view", "Commands: /", "other cameras", 'text += "Seated view'):
        check(bad not in s, f"{n}: the free build still says '{bad}'")
check('string h = "Take 12 Scenery";' in ui and "Welcome to Take 12 Scenery" in ui and "More cameras · Me, Us, Still and sharing, in the full Take 12" in ui,
      "ui: the free names and the More cameras line")
check('if (LITE) openMenu(llList2String(["live", "main"], gUiState == "idle"));' in ui, "Hold must open the menu in the free build (there is no sharing)")
check('if (id == "full") { closeMenu(); upsell(); return; }' in ui and "llLoadURL(gOwner" in ui, "More cameras must open the full Take 12's listing")
check('if (gIndoors == "outside") raw = FALSE;' in sc, "scenery: skybox rooms must work in the free build")
check("!LITE && gCuts % 4 == 3" in sc and "num == FAV && !LITE" in sc, "scenery: no favourites in the free build")
check('if (LITE && (str == "personal" || str == "social" || str == "friends" || str == "frame" || str == "fav")) return;' in core,
      "core: the free build must refuse the other cameras")
# its own button (scenery/art): one design, so no Button choice under Options > Look
check('"th0"' not in ui and " · Button: " not in ui and "menu style, button" not in ui, "ui: the free build has one button design, no Button choice")
readme = rd("scenery", "README.md")
check("scenery/art/take12_scenery_icon_sheet_512x256.png" in readme and "hud/art/take12_icon_sheet" not in readme, "scenery/README.md must name the Scenery texture")
check(os.path.exists(os.path.join(R, "scenery", "art", "take12_scenery_icon_sheet_512x256.png")), "the Scenery texture is missing")
# the notecard the HUD looks for is the one shipped with it
nc = re.search(r'string NOTECARD = "([^"]+)";', ui).group(1)
check(nc == "Take 12 Scenery - Read Me" and "Read Me" in nc, f"ui: notecard name {nc}")
check(os.path.exists(os.path.join(R, "scenery", "notecard", "read_me.txt")), "scenery/notecard/read_me.txt is missing")
card = rd("scenery", "notecard", "read_me.txt")
check(card.startswith("Take 12 Scenery") and "Lite" not in card and "HOLD" in card and "full Take 12" in card and "Viewfinder" not in card, "the free Read Me")
vers = {re.search(r'string VERSION = "([^"]+)";', rd("hud", "src", n)).group(1) for n in os.listdir(os.path.join(R, "hud", "src"))}
check(len(vers) == 1, f"hud/src: every script must carry the same version (the ui warns otherwise): {vers}")
# the tips keep their numbers (tips.lsl picks them by index)
cnt = lambda s: s[s.index("list TIPS = ["):s.index("];", s.index("list TIPS = ["))].count('",') + 1
check(cnt(tips) == cnt(rd("hud", "src", "tips.lsl")), "tips: the free build must keep every tip in its place")
print(f"free: 4 scripts generated from hud/src, {changed} lines changed (the switch and the texts)")
print("free checks:", "ALL PASS" if ok else "FAILURES")
raise SystemExit(0 if ok else 1)
